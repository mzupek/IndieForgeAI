import { mkdir, writeFile } from 'fs/promises'
import { dirname, join } from 'path'
import type { IndieForgeProject } from '@shared/types/project'
import { loadProject } from '../storage/projectStore'

function fill(template: string, project: IndieForgeProject): string {
  return template
    .replaceAll('{{NAME}}', project.name)
    .replaceAll('{{DESCRIPTION}}', project.description)
    .replaceAll('{{ENGINE}}', project.engine)
    .replaceAll('{{CRAFT_PATH}}', project.craftPath)
    .replaceAll('{{PLATFORM}}', project.targetPlatform)
    .replaceAll('{{ART_STYLE}}', project.styleGuide.artStyle)
    .replaceAll('{{PALETTE}}', project.styleGuide.colorPalette ?? '(define palette)')
    .replaceAll('{{NOTES}}', project.styleGuide.notes || '(none)')
}

const SHARED_README = `# Studio Kit for {{NAME}}

Generated by Indie Forge — copy this folder into your **{{ENGINE}}** game repo (or merge \`docs/\` and \`.cursor/rules/\`).

## How to work

1. Keep Indie Forge as the content / production brain (scenes, assets, craft stages).
2. Use Cursor in this engine repo with the rules under \`.cursor/rules/\`.
3. Install recommended MCPs from \`mcp/RECOMMENDED.md\` in Cursor — Indie Forge does not host them.
4. Prefer proven packages from \`packages/\` — do not reinvent tween/async/DI.

Workflow: **plan in Indie Forge → craft/export assets → Cursor agents implement in {{ENGINE}}**.
`

const GAME_VISION = `# Game Vision — {{NAME}}

{{DESCRIPTION}}

- Engine: **{{ENGINE}}**
- Craft path: **{{CRAFT_PATH}}**
- Platform: {{PLATFORM}}
`

const ART_DIRECTION = `# Art Direction — {{NAME}}

- Style: {{ART_STYLE}}
- Palette: {{PALETTE}}
- Notes: {{NOTES}}

## Rules

- Pixel (Godot) projects: readable silhouettes first; nearest filtering; no baked bloom.
- Unity neon projects: emission + shared bloom volume; do not bake glow into every texture.
`

const SPRITE_PIPELINE_GODOT = `# Sprite Pipeline — {{NAME}} (Godot)

1. Silhouette in Indie Forge Craft Studio (or Aseprite).
2. Color / polish in Craft Studio or Aseprite.
3. Export atlas / frames from Indie Forge.
4. Import under \`res://assets/\` with **Filter = Nearest**, mipmaps off.
5. Use Sprite2D / AnimatedSprite2D; pivots from Indie Forge contracts (often bottom_center).
`

const SPRITE_PIPELINE_UNITY = `# Asset Pipeline — {{NAME}} (Unity)

1. Plan tile states / FX in Indie Forge Production.
2. Implement as URP materials + material instances (color properties for magenta/cyan/lime).
3. Shared Volume bloom — not per-texture bloom bake.
4. VFX: small additive stamps in Shuriken/VFX Graph.
5. Import any masks/sprites with appropriate filter (UI often bilinear; pixel stamps nearest if used).
`

const ENGINE_ARCH_GODOT = `# Engine Architecture — {{NAME}} (Godot 4)

Prefer **systems**, not god-objects:

- InputSystem / CallSystem / ScoreSystem / Audio (autoload) / Save (autoload)
- Events via signals or a thin EventBus autoload
- Scenes composed from Indie Forge scene contracts

Ask before adding large addons. Prefer first-party Tween and autoloads.
`

const ENGINE_ARCH_UNITY = `# Engine Architecture — {{NAME}} (Unity)

Prefer **systems** folders:

- Combat/Grid/Input/Audio/Save/UI — not mega Player.cs
- ScriptableObject event channels for decoupling
- Level data as ScriptableObjects

Recommended packages: see \`packages/UNITY_RECOMMENDED.md\` (UniTask, DOTween, etc.).
`

const PERF = `# Performance Rules — {{NAME}} (Mobile)

- Atlas where possible; watch texture sizes
- Limit overdraw (especially bloom / particles)
- Avoid allocations in Update / _process hot paths
- Profile on device, not only editor
`

const CURSOR_WORKFLOW = `# Cursor Workflow — {{NAME}}

1. Read \`docs/\` before coding.
2. Use the matching \`.cursor/rules/\` agent persona for the task.
3. Claude (or chat) plans → Cursor executes → review diff.
4. MCP: use Unity/Godot-aware tools when available; otherwise filesystem + git.
`

function agentRule(name: string, body: string): string {
  return `---
description: ${name} for {{NAME}}
globs:
alwaysApply: false
---

# ${name}

${body}
`
}

export async function exportStudioKit(
  projectId: string,
  exportDir: string
): Promise<{ path: string; files: string[] }> {
  const project = await loadProject(projectId)
  const root = join(exportDir, `studio-kit-${project.engine}`)
  const files: string[] = []

  const write = async (rel: string, content: string) => {
    const full = join(root, rel)
    await mkdir(dirname(full), { recursive: true })
    await writeFile(full, fill(content, project), 'utf-8')
    files.push(rel)
  }

  await mkdir(root, { recursive: true })
  await write('README.md', SHARED_README)
  await write('docs/GAME_VISION.md', GAME_VISION)
  await write('docs/ART_DIRECTION.md', ART_DIRECTION)
  await write(
    'docs/SPRITE_PIPELINE.md',
    project.engine === 'godot' ? SPRITE_PIPELINE_GODOT : SPRITE_PIPELINE_UNITY
  )
  await write(
    'docs/ENGINE_ARCHITECTURE.md',
    project.engine === 'godot' ? ENGINE_ARCH_GODOT : ENGINE_ARCH_UNITY
  )
  await write('docs/PERFORMANCE_RULES.md', PERF)
  await write('docs/CURSOR_WORKFLOW.md', CURSOR_WORKFLOW)

  await write(
    '.cursor/rules/gameplay-engineer.mdc',
    agentRule(
      'Gameplay Engineer',
      'Implement mechanics, input, save, scoring. Never invent art pipelines. Follow ENGINE_ARCHITECTURE.md. Mobile-first.'
    )
  )
  await write(
    '.cursor/rules/graphics-engineer.mdc',
    agentRule(
      'Graphics Engineer',
      project.engine === 'unity'
        ? 'Materials, URP bloom, VFX, lighting. Prefer material instances and shared post volumes.'
        : 'Shaders, canvas items, modulate, light2d sparingly. Nearest-filter sprites from Indie Forge.'
    )
  )
  await write(
    '.cursor/rules/animation-pipeline.mdc',
    agentRule(
      'Animation / Asset Pipeline',
      'Import Indie Forge sheets, set pivots, SpriteFrames / Animator wiring. Do not regenerate art with random AI prompts.'
    )
  )
  await write(
    '.cursor/rules/performance-mobile.mdc',
    agentRule('Performance (Mobile)', 'Catch GC, overdraw, oversized textures, draw calls. See PERFORMANCE_RULES.md.')
  )
  await write(
    '.cursor/rules/qa-consistency.mdc',
    agentRule('QA Consistency', 'Naming, docs compliance, edge cases before merge. Reference GAME_VISION.md.')
  )

  await write(
    'mcp/RECOMMENDED.md',
    project.engine === 'unity'
      ? `# MCP servers (Cursor) — Unity

Indie Forge does **not** host these. Install in Cursor for the **game repo**:

- **Unity MCP** — scenes, prefabs, console (when available for your Unity version)
- **Filesystem** — asset search
- **Git / GitHub** — branches, PRs, issues

Use MCPs so agents inspect the editor, not only source text.
`
      : `# MCP servers (Cursor) — Godot

Indie Forge does **not** host these. Install in Cursor for the **game repo**:

- **Filesystem** — \`res://\` asset search
- **Git / GitHub** — branches, PRs
- Godot-oriented MCP if you adopt one — otherwise agents work from \`.tscn\` / \`.gd\` text

Use MCPs to reduce blind edits.
`
  )

  await write(
    'packages/UNITY_RECOMMENDED.md',
    `# Unity packages (recommend — do not reinvent)

- UniTask — async without coroutine pain
- DOTween — tweening
- ScriptableObject event channels or MessagePipe — decoupling
- Newtonsoft.Json or Easy Save — persistence
- Odin Inspector — optional productivity (paid)

Only add what the project needs.
`
  )

  await write(
    'packages/GODOT_RECOMMENDED.md',
    `# Godot patterns (recommend)

- Autoloads for Audio / Save / Events
- Built-in Tween
- Signal-based decoupling
- SpriteFrames for animations from Indie Forge sheets

Avoid heavy addon stacks unless justified.
`
  )

  return { path: root, files }
}
